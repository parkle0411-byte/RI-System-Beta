import re
from playwright.sync_api import sync_playwright, expect

def field(page, label):
    return page.locator('.el-form-item').filter(has=page.locator('.el-form-item__label', has_text=re.compile(r'^\s*' + re.escape(label) + r'\s*$'))).first

def pick(page, label, value):
    field(page, label).locator('.el-select__wrapper').first.click()
    page.locator('.el-select__popper[aria-hidden="false"] .el-select-dropdown__item').filter(has_text=value).first.click()

def fill(page, label, value):
    item = field(page, label).locator('input, textarea').first
    item.fill(value); item.press('Tab')

