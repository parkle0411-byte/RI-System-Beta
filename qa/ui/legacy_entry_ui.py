# Loaded by ui_test.py so ordinary login, form and console checks are shared.
def phase_l(page):
    login(page,'ui.legacy.sales')
    goto(page,BASE+'/legacy')
    check('Legacy tab and heading use the requested English name',page.get_by_role('heading',name='Legacy Data (Old Register)',exact=True).count()==1)
    page.locator('.legacy-toolbar input').fill('UI-LEGACY-REF')
    page.get_by_role('button',name='Search',exact=True).click();wait_api_idle(page)
    page.get_by_role('button',name='UI-OLD-1',exact=True).click()
    page.get_by_role('button',name='New Endorsement',exact=True).click()
    page.locator('.entry-form').wait_for();wait_api_idle(page)
    dlg=page.locator('.el-dialog').filter(has=page.locator('.entry-form')).last
    check('endorsement form includes premium and percentages',item(dlg,page,'100% Premium (This Endorsement Adjustment)').count()==1 and item(dlg,page,'R/I Commission (%)').count()==1)
    # 2026-11-12: Cedant, Settlement Party, currency follow the source; the payment rule is detected.
    check('endorsement keeps the source Cedant, Settlement Party and currency',all(item(dlg,page,l).locator('input').first.is_disabled() for l in ('Cedant','Settlement Party'))
          and item(dlg,page,'Currency').locator('.is-disabled').count()>0 and 'UI Re Alpha' in item(dlg,page,'Settlement Party').locator('input').first.input_value())
    check('payment rule is detected, not chosen',item(dlg,page,'Payment Rule').locator('input').first.input_value()=='Ordinary legacy counterparty')
    fill(dlg,page,'100% Premium (This Endorsement Adjustment)',1000)
    fill(dlg,page,'R/I Commission (%)',15);fill(dlg,page,'Tax (%)',1)
    fill(dlg,page,'Brokerage Amount (Original Currency)',50)
    fill(dlg,page,'Endorsement No.','E-UI-01')
    check('Revenue Month is automatic',item(dlg,page,'Revenue Month (automatic)').count()==1)
    dlg.get_by_role('button',name='Save Draft',exact=True).click();wait_api_idle(page)
    check('saved draft has matching calculated amounts','840' in dlg.inner_text() and '790' in dlg.inner_text())
    dlg.get_by_role('button',name='Confirm Transaction',exact=True).click();wait_api_idle(page)
    check('endorsement confirmation closes the editor',not page.locator('.entry-form').is_visible())
    check('missing FX is marked without preventing confirmation',page.get_by_text('Awaiting FX',exact=True).count()>0)
    page.get_by_role('button',name='UI-OLD-1',exact=True).click()
    page.get_by_role('button',name='New Claim',exact=True).click()
    page.locator('.entry-form').wait_for();wait_api_idle(page)
    dlg=page.locator('.el-dialog').filter(has=page.locator('.entry-form')).last
    check('claim has no Revenue Month or brokerage input',item(dlg,page,'Revenue Month').count()==0 and item(dlg,page,'Brokerage Amount (Original Currency)').count()==0)
    check('claim keeps the source Insured and Old Reference',item(dlg,page,'Old Reference').locator('input').first.is_disabled() and item(dlg,page,'Insured (English)').locator('input').first.is_disabled())
    fill(dlg,page,'Loss No.','UI-LOSS-1');fill(dlg,page,'Cause of Loss','Fire')
    date(dlg,page,'DOL','2035-05-01');fill(dlg,page,'Claim Amount (Our Share)',-5000)
    fill(dlg,page,'Negative Claim Reason','Return excess claim payment')
    fill(dlg,page,'Note for Claim','Claim handling note retained for follow-up')
    dlg.get_by_role('button',name='Confirm Transaction',exact=True).click();wait_api_idle(page)
    check('negative claim confirmation succeeds',not page.locator('.entry-form').is_visible())
    check('both new transactions retain unique final LTX numbers',page.locator('.legacy-page .el-table__body-wrapper').first.inner_text().count('LTX-')==2)
    page.get_by_role('button',name=re.compile(r'^LTX-')).first.click()
    detail=page.locator('.el-dialog:visible').last
    check('confirmed claim details retain DOL and return reason','2035-05-01' in detail.inner_text() and 'Return excess claim payment' in detail.inner_text() and 'Claim handling note retained for follow-up' in detail.inner_text())
    check('claim details show Loss No., Cause of Loss and the same-Loss No. list','UI-LOSS-1' in detail.inner_text() and 'Fire' in detail.inner_text() and page.get_by_test_id('legacy-loss-group').count()==1)
    detail.get_by_role('button',name='Close',exact=True).click()
    snap(page,'legacy-transactions-confirmed')
    logout(page);login(page,'ui.legacy.finance');goto(page,BASE+'/legacy')
    page.get_by_role('button',name='UI-OLD-1',exact=True).click()
    check('Finance can read but cannot create business transactions',page.get_by_role('button',name='New Claim',exact=True).count()==0 and page.get_by_role('button',name='New Endorsement',exact=True).count()==0)
    page.get_by_role('button',name='Close',exact=True).last.click()
    goto(page,BASE+'/accounting');wait_api_idle(page)
    check('new Legacy transactions are available in Accounting','UI-LEGACY-REF' in page.locator('[data-testid="accounting-table"]').inner_text())
    claim_row=page.locator('.el-table__body-wrapper tr').filter(has_text=re.compile(r'LTX-.*-C1-T1')).first
    party_cell=claim_row.locator('.cell').filter(has_text='UI Re Alpha').first
    check('negative claim payables name the reinsurer correctly','UI Re Alpha' in party_cell.inner_text() and 'Payable' in party_cell.inner_text())
    check('Accounting shows the claim Loss No.','Loss No. UI-LOSS-1' in page.locator('[data-testid="accounting-table"]').inner_text())
    snap(page,'legacy-accounting')
    # 2026-11-25: a never-confirmed draft can be deleted (owner or System Administrator, reason required).
    def open_list():
        goto(page,BASE+'/legacy')
        page.locator('.legacy-toolbar input').fill('UI-LEGACY-REF')
        page.get_by_role('button',name='Search',exact=True).click();wait_api_idle(page)
    drafts=lambda:page.locator('.legacy-page .el-table__body-wrapper').first.get_by_role('button',name='Draft',exact=True)
    def new_draft(kind):
        page.get_by_role('button',name='UI-OLD-1',exact=True).click()
        page.get_by_role('button',name=kind,exact=True).click()
        page.locator('.entry-form').wait_for();wait_api_idle(page)
    def delete_box():
        return page.locator('.el-dialog:visible').filter(has=page.get_by_text('Deletion Reason')).last
    logout(page);login(page,'ui.legacy.sales');open_list()
    page.get_by_role('button',name='UI-OLD-1',exact=True).click();wait_api_idle(page)
    check('a confirmed transaction offers no Delete Draft',page.get_by_test_id('legacy-delete-draft').count()==0)
    page.locator('.el-dialog:visible').last.get_by_role('button',name='Close',exact=True).click()
    new_draft('New Endorsement')
    page.get_by_test_id('legacy-editor-delete').click();box=delete_box();box.wait_for()
    confirm=box.get_by_role('button',name='Delete Draft',exact=True)
    check('the editor opens a delete dialog that needs a reason',confirm.is_disabled() and 'permanently deletes' in box.inner_text())
    box.locator('textarea').fill('   ')
    check('a blank reason does not enable deletion',confirm.is_disabled())
    box.locator('textarea').fill('UI wrong draft');snap(page,'legacy-delete-dialog');confirm.click();wait_api_idle(page)
    page.locator('.el-message',has_text='Draft deleted.').first.wait_for()
    page.wait_for_timeout(600)
    check('deleting from the editor closes it and removes the draft',not page.locator('.entry-form').is_visible() and drafts().count()==0)
    new_draft('New Claim')
    page.locator('.el-dialog:visible').last.get_by_role('button',name='Close',exact=True).click();wait_api_idle(page);open_list()
    check('a closed draft stays in the list',drafts().count()==1)
    drafts().first.click();wait_api_idle(page)
    page.get_by_test_id('legacy-delete-draft').click();box=delete_box();box.wait_for()
    box.get_by_role('button',name='Cancel',exact=True).click();page.wait_for_timeout(600)
    check('Cancel keeps the draft',page.get_by_test_id('legacy-delete-draft').is_visible() and drafts().count()==1)
    page.get_by_test_id('legacy-delete-draft').click();box=delete_box();box.wait_for()
    check('the reason starts empty again',box.locator('textarea').input_value()=='' and box.get_by_role('button',name='Delete Draft',exact=True).is_disabled())
    box.locator('textarea').fill('UI claim keyed twice');box.get_by_role('button',name='Delete Draft',exact=True).click();wait_api_idle(page)
    page.wait_for_timeout(600)
    check('deleting from the detail window closes it and removes the draft',page.locator('.el-dialog:visible').count()==0 and drafts().count()==0)
    new_draft('New Endorsement')
    page.locator('.el-dialog:visible').last.get_by_role('button',name='Close',exact=True).click();wait_api_idle(page)
    logout(page);login(page,'ui.legacy.finance');open_list()
    drafts().first.click();wait_api_idle(page)
    check('Finance cannot delete a draft',page.get_by_test_id('legacy-delete-draft').count()==0)
    page.locator('.el-dialog:visible').last.get_by_role('button',name='Close',exact=True).click()
    logout(page);login(page,'ui.admin');open_list()
    drafts().first.click();wait_api_idle(page)
    check("a System Administrator may delete another user's draft",page.get_by_test_id('legacy-delete-draft').count()==1)
    page.get_by_test_id('legacy-delete-draft').click();box=delete_box();box.wait_for()
    box.locator('textarea').fill('UI administrator cleanup');box.get_by_role('button',name='Delete Draft',exact=True).click();wait_api_idle(page)
    page.wait_for_timeout(600)
    check('the administrator deletion removes it',drafts().count()==0)
    logout(page);login(page,'ui.admin');goto(page,BASE+'/legacy')
    page.get_by_role('button',name='Endorsement Reasons',exact=True).click()
    page.get_by_role('button',name='Add New Reason',exact=True).click()
    dlg=page.locator('.el-dialog').filter(has=page.get_by_role('button',name='Save Reason',exact=True)).last
    fill(dlg,page,'English Label','UI Additional Endorsement Reason')
    dlg.get_by_role('button',name='Save Reason',exact=True).click();wait_api_idle(page)
    page.get_by_role('button',name='Endorsement Reasons',exact=True).click()
    page.locator('.el-dialog:visible .el-select__wrapper').first.click()
    check('administrator can add a reason over the existing HTTP deployment',page.get_by_text('UI Additional Endorsement Reason',exact=True).count()>0)
    page.keyboard.press('Escape')
    snap(page,'legacy-reason-configuration')
    goto(page,BASE+'/dashboard');logout(page)
