const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const src = fs.readFileSync(path.join(__dirname, '../src/alpha/cglInformation.js'), 'utf8')
const start = src.indexOf('export function cglTurnoverDocumentText(')
const end = src.indexOf('\nexport function initializeCglAggregate(', start)
assert.ok(start >= 0 && end > start, 'document formatter exists')
const formatter = new Function('newCgl', 'recallScope', `${src.slice(start, end).replace('export function', 'function')}\nreturn cglTurnoverDocumentText`)(() => true, () => false)
const item = (region, currency, amount, regionOther = '') => ({ region, currency, amount, regionOther })
const format = (currency, entries) => formatter({ currency, cglInformation: { estimatedTurnover: entries } })
assert.equal(format('USD', [item('USA/Canada', 'USD', 10)]), 'USA/Canada · USD 10')
assert.equal(format('USD', [item('Rest of World', 'TWD', 50), item('USA/Canada', 'USD', 0.1), item('Other', 'USD', 0.2, 'Europe')]),
  'Total · USD 0.3\nUSA/Canada · USD 0.1\nEurope · USD 0.2\nTotal · TWD 50\nRest of World · TWD 50')
assert.equal(format('TWD', []), '—')
console.log('CGL cover turnover formatting: passed')
