import { apiFetch } from '../../api'

const pendingFiles = new Map()

export function usesStoredQsWord(kind, c) {
  return ['cover', 'debit'].includes(kind) && c?.reinsuranceStructure === 'QS' && !c?.parentTwRef
    && (c?.classCode === 'PD' || c?.classOfBusiness === 'Property')
}

export async function readDocumentError(response, fallback) {
  const body = await response.json().catch(() => ({}))
  const error = new Error(body.message || body.error || fallback)
  error.issues = Array.isArray(body.issues) ? body.issues : []
  return error
}

function generationId() {
  if (typeof globalThis.crypto?.randomUUID === 'function') return globalThis.crypto.randomUUID()
  // getRandomValues is available on the existing HTTP intranet, unlike randomUUID.
  const bytes = globalThis.crypto.getRandomValues(new Uint8Array(16))
  bytes[6] = (bytes[6] & 15) | 64
  bytes[8] = (bytes[8] & 63) | 128
  const hex = Array.from(bytes, value => value.toString(16).padStart(2, '0')).join('')
  return [hex.slice(0, 8), hex.slice(8, 12), hex.slice(12, 16), hex.slice(16, 20), hex.slice(20)].join('-')
}

function encodeFile(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result).split(',')[1])
    reader.onerror = () => reject(new Error('The generated Word file could not be read. Generate it again.'))
    reader.readAsDataURL(blob)
  })
}

export async function saveAndDownloadQsWord(kind, c, generate) {
  const key = c.caseUid + ':' + kind
  const signature = JSON.stringify(c)
  let file = pendingFiles.get(key)
  if (!file || file.signature !== signature) {
    pendingFiles.delete(key)
    file = {
      signature, blob: await generate(), id: generationId(),
      filename: window.RIDocx[kind === 'cover' ? 'coverFilename' : 'debitFilename'](c),
    }
    pendingFiles.set(key, file)
  }
  file.base64 = file.base64 || await encodeFile(file.blob)
  let saved
  try {
    saved = await apiFetch('/api/generated-case-documents', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
    body: JSON.stringify({
      caseUid: c.caseUid, kind, generationId: file.id, rowVersion: c.caseRowVersion,
      filename: file.filename, base64: file.base64,
    }),
  })
  } catch (cause) {
    throw new Error('The Word file could not be saved to Case Documents. No file was downloaded. Generate again to retry saving.', { cause })
  }
  if (!saved.ok) {
    const error = await readDocumentError(saved, 'The Word file could not be saved.')
    error.message += ' No file was downloaded. Generate again to retry saving.'
    throw error
  }
  // The same generated bytes and id are reused after a lost response or a failed save.
  window.RIDocx.downloadBlob(file.blob, file.filename)
  pendingFiles.delete(key)
  return saved.json()
}
